/**
 * Deterministically pick a fort preset name based on slotKey and crisis type.
 * @param {string} slotKey
 * @param {string} [crisisType]
 * @returns {string}
 */
export function pickFortPresetName(slotKey, crisisType = 'WAR') {
  const pool = CRISIS_PRESET_POOLS[crisisType] ?? CRISIS_PRESET_POOLS.WAR;
  let h = 0x811c9dc5;
  const s = String(slotKey ?? '');
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 0x01000193) >>> 0;
  return pool[bountyHash(h, 0xfa7) % pool.length];
}

/**
 * Get fort preset definition by name.
 * @param {string} name
 */
export function getFortPreset(name) {
  return FORT_PRESETS[name] ?? FORT_PRESETS['WOD_BanditFort_01'];
}
